--!strict
-- Amalgamation bundler.
--
-- Walks `src/` and emits `dist/kushanv2` as a single Lua file where each source
-- module is wrapped as a factory function in a `_MODULES` table. A `_require`
-- shim provides caching and cycle detection, and the entry module `src/init.lua`
-- is executed at the bottom.
--
-- Module keys are the source path without the `.lua` extension, using `/` as the
-- separator (e.g. `src/jobs/taxi.lua` becomes `"jobs/taxi"`).
--
-- Run from the repo root:
--     lune run build/bundle

local fs = require("@lune/fs")
local process = require("@lune/process")
local stdio = require("@lune/stdio")

local SRC_DIR = "src"
local DIST_DIR = "dist"
local OUT_FILE = DIST_DIR .. "/kushanv2"
local ENTRY = "init"

type Module = { key: string, path: string }

local function discover(dir: string, prefix: string): { Module }
  local out: { Module } = {}
  for _, entry in ipairs(fs.readDir(dir)) do
    local full = dir .. "/" .. entry
    if fs.isDir(full) then
      local sub = if prefix == "" then entry else (prefix .. "/" .. entry)
      for _, m in ipairs(discover(full, sub)) do
        table.insert(out, m)
      end
    elseif entry:sub(-4) == ".lua" then
      local name = entry:sub(1, -5)
      local key = if prefix == "" then name else (prefix .. "/" .. name)
      table.insert(out, { key = key, path = full })
    end
  end
  return out
end

local HEADER = [[
-- GENERATED BY build/bundle.lua -- DO NOT EDIT BY HAND
-- Run `lune run build/bundle` from the repo root to regenerate.

local _MODULES = {}
local _CACHE = {}
local _LOADING = {}

local function _require(name)
  local cached = _CACHE[name]
  if cached ~= nil then
    return cached
  end
  if _LOADING[name] then
    error("Circular require: " .. tostring(name), 2)
  end
  local factory = _MODULES[name]
  if not factory then
    error("Module not found: " .. tostring(name), 2)
  end
  _LOADING[name] = true
  local ok, result = pcall(factory, _require)
  _LOADING[name] = nil
  if not ok then
    error(result, 2)
  end
  if result == nil then
    result = true
  end
  _CACHE[name] = result
  return result
end
]]

local function emit(modules: { Module }): string
  local chunks: { string } = { HEADER }
  table.sort(modules, function(a: Module, b: Module)
    return a.key < b.key
  end)
  for _, m in ipairs(modules) do
    local src = fs.readFile(m.path)
    if src:sub(-1) == "\n" then
      src = src:sub(1, -2)
    end
    table.insert(chunks, string.format("_MODULES[%q] = function(require)\n%s\nend\n", m.key, src))
  end
  table.insert(chunks, string.format("_require(%q)\n", ENTRY))
  return table.concat(chunks, "\n")
end

local modules = discover(SRC_DIR, "")
if #modules == 0 then
  stdio.ewrite("No modules found under " .. SRC_DIR .. "/\n")
  process.exit(1)
end

local hasEntry = false
for _, m in ipairs(modules) do
  if m.key == ENTRY then
    hasEntry = true
    break
  end
end
if not hasEntry then
  stdio.ewrite("No entry module at src/init.lua\n")
  process.exit(1)
end

if not fs.isDir(DIST_DIR) then
  fs.writeDir(DIST_DIR)
end

local output = emit(modules)
fs.writeFile(OUT_FILE, output)
print(string.format("Bundled %d module(s) -> %s (%d bytes)", #modules, OUT_FILE, #output))
